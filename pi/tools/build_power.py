#!/usr/bin/env python3
"""The Pi's rose expansion and power tables (pi/data/power.json), from the lighting repo's own model.

Reads, never writes, a lighting checkout: pixel-map/psu_model.py (PSUs, Bright Sets, wiring-db/strands.db) and
pixel-map/expand-fseq.py (petal-config-v2.json), so pi/src/power.ts runs exactly what compress-fseq.py runs. It also
records the pixel count of City of Gods' pixel map (city-of-gods/pixel-map/out/, through tools/build_rig.py), which
the engine asserts rig.json has at startup (ADD_LIVE_APP.md: a stale map stops it).

    python3 pi/tools/build_power.py [LIGHTING]          # default LIGHTING_DIR, or lighting/ beside this repo
    python3 pi/tools/build_power.py [LIGHTING] --check  # exit 1 if power.json is stale
"""
import importlib.util
import json
import os
import sys

sys.dont_write_bytecode = True   # the lighting checkout is read-only: no __pycache__ there
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'data', 'power.json')
LIGHTING = os.environ.get('LIGHTING_DIR') or os.path.join(HERE, '..', '..', '..', 'lighting')  # tools/sources.py's


def load(lighting, name, file):
    spec = importlib.util.spec_from_file_location(name, os.path.join(lighting, 'pixel-map', file))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def pixel_count(lighting):
    """How many pixels City of Gods' pixel map has, counted as tools/build_rig.py makes rig.json."""
    os.environ['LIGHTING_DIR'] = lighting
    sys.path.insert(0, os.path.join(HERE, '..', '..', 'tools'))
    import build_rig
    return len(build_rig.build('cog')['pixels']['universe'])


def build(lighting):
    cf = load(lighting, 'compress_fseq', 'compress-fseq.py')
    pm = cf.PM
    ef = pm.EF
    segs = ef.load_petal_segments()
    petals = []
    for p in range(1, 17):
        petals.append({'src': ef.source_petal_base(p), 'exp': ef.exp_petal_base(p),
                       'segments': [[s.get('skip_before', 0), ef.CELL_INDEX[s['cell']], s['count']] for s in segs[p]]})
    psu_map = pm.build_psu_map()
    psus = []
    for pid, (bright, volts, rating, _) in pm.PSU_META.items():   # PSU_META's order: compress-fseq sums in it
        psus.append({'id': pid, 'set': bright, 'volts': volts, 'rating': rating,
                     'ranges': [[st, n, w] for st, n, w in psu_map[pid]]})
    return {'about': 'Generated by pi/tools/build_power.py from the lighting repo; do not edit.',
            'pixels': pixel_count(lighting), 'channels': ef.EXP_MAX_CHANNEL, 'cellChannels': ef.CH_PER_PIXEL,
            'petals': petals, 'psus': psus,
            'sets': cf.SETS, 'weights': cf.WEIGHTS, 'releaseFrames': cf.RELEASE_FRAMES}


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    lighting = os.path.abspath(os.path.expanduser(args[0] if args else LIGHTING))
    data = build(lighting)
    text = json.dumps(data, separators=(',', ':')) + '\n'
    if '--check' in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print('power.json is current' if same else 'power.json is stale: run pi/tools/build_power.py')
        sys.exit(0 if same else 1)
    with open(OUT, 'w') as f:
        f.write(text)
    print(f'wrote {OUT}: {len(data["psus"])} PSUs, {data["channels"]} channels')


if __name__ == '__main__':
    main()
